#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"

echo "== animation-retarget-kit setup =="

find_blender() {
	if [[ -n "${BLENDER:-}" && -x "${BLENDER}" ]]; then
		echo "${BLENDER}"
		return 0
	fi
	if [[ -x "/Applications/Blender.app/Contents/MacOS/Blender" ]]; then
		echo "/Applications/Blender.app/Contents/MacOS/Blender"
		return 0
	fi
	if command -v blender >/dev/null 2>&1; then
		command -v blender
		return 0
	fi
	# Windows + Git Bash 常见安装位置
	for candidate in "/c/Program Files/Blender Foundation"/Blender*/blender.exe "/c/Program Files"/Blender*/blender.exe; do
		if [[ -x "${candidate}" ]]; then
			echo "${candidate}"
			return 0
		fi
	done
	return 1
}

PYTHON="$(command -v python3 || command -v python || true)"
if [[ -z "${PYTHON}" ]]; then
	echo "ERROR: Python 3 is required for one-click report summaries."
	echo "Windows: https://www.python.org/downloads/ （安装时勾选 Add python.exe to PATH）"
	exit 1
fi

BLENDER_BIN="$(find_blender || true)"
if [[ -z "${BLENDER_BIN}" ]]; then
	echo "ERROR: Blender 3.4+ not found."
	if command -v brew >/dev/null 2>&1; then
		echo "macOS 安装：brew install --cask blender"
	else
		echo "下载：https://www.blender.org/download/"
	fi
	exit 1
fi

if [[ "${BLENDER_BIN}" == [A-Za-z]:* ]] && command -v cygpath >/dev/null 2>&1; then
	BLENDER_BIN="$(cygpath -u "${BLENDER_BIN}")"
fi
VERSION="$("${BLENDER_BIN}" --version | head -1 | awk '{print $2}')"
echo "Blender: ${BLENDER_BIN} (${VERSION})"
"${PYTHON}" - "${VERSION}" <<'PY'
import sys
parts = [int(x) for x in sys.argv[1].split(".")[:2]]
if parts < [3, 4]:
    print("ERROR: Blender >= 3.4 required")
    sys.exit(1)
PY

cat > config.env <<EOF
# generated by setup.sh
export BLENDER="${BLENDER_BIN}"
EOF

chmod +x setup.sh retarget.sh tools/*.sh 2>/dev/null || true
chmod +x "一键迁移.command" 2>/dev/null || true
mkdir -p out examples

echo "[1/3] inspect bundled source"
bash tools/blender_inspect.sh assets/source/Soldier.glb --require-armature > /tmp/retarget_setup_source.log 2>&1
echo "[2/3] inspect bundled target"
bash tools/blender_inspect.sh assets/target/Michelle.glb --require-armature > /tmp/retarget_setup_target.log 2>&1

if ! grep -q "^BLENDER_REPORT " /tmp/retarget_setup_source.log || ! grep -q "^BLENDER_REPORT " /tmp/retarget_setup_target.log; then
	echo "ERROR: bundled asset inspect failed"
	tail -20 /tmp/retarget_setup_source.log || true
	tail -20 /tmp/retarget_setup_target.log || true
	exit 1
fi

echo "[3/3] smoke OK"
if [[ "${1:-}" == "--full" ]]; then
	echo "== full golden example =="
	bash tools/run_example.sh
fi

echo
echo "SETUP_OK"
echo "配置已写入: ${ROOT}/config.env"
case "$(uname -s)" in
	MINGW*|MSYS*|CYGWIN*) echo "一键迁移: 双击 windows/retarget.bat" ;;
	*) echo "一键迁移: 双击 一键迁移.command" ;;
esac
echo "命令行:   ./retarget.sh --target /path/your.fbx --clip samba"
